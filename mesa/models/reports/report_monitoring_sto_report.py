# -*- coding: utf-8 -*-
import logging
from odoo import models, fields, api

_logger = logging.getLogger(__name__)

class ReportMonitoringSTO(models.Model):
    """
    Tabel fisik (bukan transient) menyimpan hasil generate Report Monitoring STO sementara per user.
    """
    _name = 'report.monitoring.sto'
    _description = 'Report Monitoring STO Buffer'
    _order = 'date desc, id'

    # Filter/Ownership logic
    user_id = fields.Many2one('res.users', string='Generated By', index=True, required=True, ondelete='cascade')

    # Dates
    date = fields.Datetime(string='STO Date', index=True, store=True)

    # References
    transfer_id = fields.Many2one('snk.stock.transfer.order', string='PR / STO Ref', index=True)
    transfer_line_id = fields.Many2one('snk.stock.transfer.order.line', string='STO Line', index=True)
    delivery_picking_id = fields.Many2one('stock.picking', string='Delivery Ref', index=True)
    delivery_date = fields.Datetime(string='Delivery Date', index=True, related='delivery_picking_id.scheduled_date', store=True)
    physical_delivery_date = fields.Datetime(string='Physical Delivery Date', index=True, related='delivery_picking_id.snk_physical_date', store=True)
    delivery_done_date = fields.Datetime(string='Delivery Done Date', index=True, related='delivery_picking_id.date_done', store=True)
    delivery_status = fields.Selection(string='Status DO', related='delivery_picking_id.state', store=True)
    receipt_picking_id = fields.Many2one('stock.picking', string='Receipt Ref', index=True)
    receipt_date = fields.Datetime(string='Receipt Date', index=True, related='receipt_picking_id.scheduled_date', store=True)
    physical_receipt_date = fields.Datetime(string='Physical Receipt Date', index=True, related='receipt_picking_id.snk_physical_date', store=True)
    receipt_done_date = fields.Datetime(string='Receipt Done Date', index=True, related='receipt_picking_id.date_done', store=True)
    receipt_status = fields.Selection(string='Status GR', related='receipt_picking_id.state', store=True)
    
    # POS Info
    snk_pos_ref = fields.Char(string='POS Document', index=True)
    pos_status_site = fields.Selection([("inactive","Inactive"),("active","Active"),("gudang","Gudang")], string='POS Status Site')

    # Product Info
    product_template_id = fields.Many2one('product.template', string='Product Template', index=True)
    product_tmpl_default_code = fields.Char(string='Template Reference', related='product_template_id.default_code', store=True)
    product_id = fields.Many2one('product.product', string='Product Variant', index=True)
    product_default_code = fields.Char(string='Variant Reference', related='product_id.default_code', store=True)
    analytic_id = fields.Many2one('account.analytic.account', string='Brand', index=True)
    snk_grade_id = fields.Many2one('snk.product.grade', string='Grade', index=True)
    category_id = fields.Many2one('product.category', string='Category', index=True)
    snk_material_code = fields.Char(string='Material Code', index=True)
    
    # Locations
    source_site_id = fields.Many2one('snk.site', string='Source Site', index=True)
    destination_site_id = fields.Many2one('snk.site', string='Destination Site', index=True)

    # Qty Tracking (Absolute Values)
    pr_demand_qty = fields.Float(string='PR Demand Qty', digits='Product Unit of Measure')
    pr_actual_qty = fields.Float(string='PR Actual Qty', digits='Product Unit of Measure')

    do_initial_qty = fields.Float(string='DO Initial Qty', digits='Product Unit of Measure')
    do_actual_qty = fields.Float(string='DO Qty Done', digits='Product Unit of Measure')

    in_initial_qty = fields.Float(string='Receipt Initial Qty', digits='Product Unit of Measure')
    in_actual_qty = fields.Float(string='Receipt Qty Done', digits='Product Unit of Measure')

    # Source & Received Tracking
    source_document = fields.Char(string='Source Document', index=True)
    received_qty = fields.Float(string='Received Qty', digits='Product Unit of Measure')
    actual_received_qty = fields.Float(string='Actual Received Qty', digits='Product Unit of Measure')

    # Pricing
    unit_price = fields.Float(string='Unit Price', digits='Product Price')
    total_amount = fields.Float(string='Total Amount', compute='_compute_total_amount', store=True, digits='Product Price')

    # Gaps / Variance
    gap_pr = fields.Float(string='Gap PR', compute='_compute_gaps', store=True, digits='Product Unit of Measure', help="PR Demand - PR Actual")
    gap_delivery = fields.Float(string='Gap Delivery', compute='_compute_gaps', store=True, digits='Product Unit of Measure', help="DO Initial - DO Actual")
    gap_receipt = fields.Float(string='Gap Receipt', compute='_compute_gaps', store=True, digits='Product Unit of Measure', help="Receipt Initial - Receipt Actual")

    # Fulfillment
    fulfillment_rate = fields.Float(string='Fulfillment Rate', compute='_compute_fulfillment_rate', store=True, group_operator='avg', help="End-to-end fulfillment percentage.")

    @api.depends('do_actual_qty', 'unit_price')
    def _compute_total_amount(self):
        for rec in self:
            rec.total_amount = rec.do_actual_qty * rec.unit_price

    @api.depends('pr_demand_qty', 'pr_actual_qty', 'do_initial_qty', 'do_actual_qty', 'in_initial_qty', 'in_actual_qty')
    def _compute_gaps(self):
        for rec in self:
            rec.gap_pr = rec.pr_demand_qty - rec.pr_actual_qty
            rec.gap_delivery = rec.do_initial_qty - rec.do_actual_qty
            rec.gap_receipt = rec.in_initial_qty - rec.in_actual_qty

    @api.depends('pr_demand_qty', 'do_initial_qty', 'in_actual_qty')
    def _compute_fulfillment_rate(self):
        for rec in self:
            base_demand = rec.pr_demand_qty if rec.pr_demand_qty > 0 else rec.do_initial_qty
            if base_demand > 0:
                rec.fulfillment_rate = rec.in_actual_qty / base_demand
            else:
                rec.fulfillment_rate = 0.0

    @api.model
    def _clean_previous_reports(self):
        """ Membersihkan report lama untuk user yang sedang login agar tidak memakan storage server """
        _logger.info("Cleaning previous STO report for user: %s (ID: %s)", self.env.user.name, self.env.uid)
        self.search([('user_id', '=', self.env.uid)]).unlink()
