# -*- coding: utf-8 -*-

from odoo import models, fields, api

class ReportStockBalanceSiteGudang(models.Model):
    _name = 'report_stock_balance_site_gudang'
    _description = 'Report Stock Balance Site vs Gudang'
    _order = 'product_id, id'

    user_id = fields.Many2one('res.users', string='Generated By', index=True, required=True, ondelete='cascade')
    
    site_id = fields.Many2one('snk.site', string='Site', index=True)
    site_name = fields.Char(string='Site Name', related='site_id.snk_name', store=True)
    location_id = fields.Many2one('stock.location', string='Location', index=True)
    product_id = fields.Many2one('product.product', string='Product', index=True)
    internal_ref = fields.Char(string='Variant Reference', related='product_id.default_code', store=True)
    snk_grade_id = fields.Many2one('snk.product.grade', string='Grade', related='product_id.snk_grade_id', store=True)
    analytic_id = fields.Many2one('account.analytic.account', string='Brand', related='product_id.analytic_id', store=True)
    snk_material_code = fields.Char(string='Material Code', related='product_id.snk_material_code', store=True)
    lot_name = fields.Char(string='Lot/Serial Number', index=True)
    categ_id = fields.Many2one('product.category', string='Category', related='product_id.categ_id', store=True)
    product_tmpl_id = fields.Many2one('product.template', string='Product Template', related='product_id.product_tmpl_id', store=True)
    tmpl_internal_ref = fields.Char(string='Template Reference', related='product_tmpl_id.default_code', store=True)

    qty_available = fields.Float(string='Available Qty', digits='Product Unit of Measure')
    stock_gudang = fields.Float(string='Stock Gudang', digits='Product Unit of Measure')
    incoming_qty = fields.Float(string='Incoming', digits='Product Unit of Measure')
    outgoing_qty = fields.Float(string='Outgoing', digits='Product Unit of Measure')
    price_unit = fields.Float(string='Sales Price', digits='Product Price')

    @api.model
    def _clean_previous_reports(self):
        self.search([('user_id', '=', self.env.uid)]).unlink()
