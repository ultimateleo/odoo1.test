# -*- coding: utf-8 -*-
import logging
from odoo import models, fields, api

_logger = logging.getLogger(__name__)

class SnkReportStockCard(models.Model):
    """
    Tabel fisik (bukan transient) menyimpan hasil generate stock card sementara per user.
    Ini merupakan best practice untuk report dengan data jutaan baris (jutaan historis move line).
    Daripada membebani memory ram dengan model Transient, PostgreSQL Indexing Odoo
    akan memastikan list/search view di UI berjalan dengan cepat.
    """
    _name = 'snk.report.stock.card'
    _description = 'Stock Card Report Buffer'
    # Default order based on standard stock cards
    _order = 'product_id, location_id, date, id'

    # Filter/Ownership logic to clear data per-user accurately
    # index=True is critical for fast querying in large table loads
    user_id = fields.Many2one('res.users', string='Generated By', index=True, required=True, ondelete='cascade',
                              help="Mengidentifikasi user mana yang men-generate data, untuk dihapus saat generate ulang.")

    # Core report parameters
    date = fields.Datetime(string='Date', index=True)
    reference = fields.Char(string='Reference/Document', index=True)
    
    # 1. Product Template Reference -> table product_template
    product_template_id = fields.Many2one('product.template', string='Product Template Reference', index=True)
    
    # 2. Product Reference -> table product_product
    product_id = fields.Many2one('product.product', string='Product Reference', index=True)
    
    # 3. Brand -> analytic_id (table account_analytic_account)
    analytic_id = fields.Many2one('account.analytic.account', string='Brand', index=True)
    
    # 4. Grade -> snk_grade_id (table snk_product_grade)
    snk_grade_id = fields.Many2one('snk.product.grade', string='Grade', index=True)
    
    # 5. Product Category -> product_category
    category_id = fields.Many2one('product.category', string='Product Category', index=True)
    
    # 6. Material Code -> snk_material_code (table product_product)
    snk_material_code = fields.Char(string='Material Code', index=True)
    
    # 7. Site -> table snk_site
    site_id = fields.Many2one('snk.site', string='Site', index=True)

    # Lokasi dan Lot
    location_id = fields.Many2one('stock.location', string='Location', index=True)
    lot_id = fields.Many2one('stock.lot', string='Lot/Serial Number', index=True)

    # Qty Tracking (Pergerakan dan Saldo Running)
    initial_balance = fields.Float(string='Initial Balance', digits='Product Unit of Measure',
                                   help="Saldo awal sebelum baris transaksi ini.")
    qty_in = fields.Float(string='Qty In', digits='Product Unit of Measure')
    qty_out = fields.Float(string='Qty Out', digits='Product Unit of Measure')
    balance = fields.Float(string='Balance', digits='Product Unit of Measure',
                           help="Running Balance Stock berdasarkan produk dan location.", index=True)
    
    # New Snapshot and Context Fields
    date_done = fields.Datetime(string='Effective Date', index=True)
    origin = fields.Char(string='Source Document', index=True)
    incoming_qty = fields.Float(string='Incoming Qty', digits='Product Unit of Measure', help="Total pending incoming goods at this site for the product.")

    @api.model
    def _clean_previous_reports(self):
        """ Membersihkan report lama untuk user yang sedang login agar tidak memakan storage server """
        _logger.info("Cleaning previous report for user: %s (ID: %s)", self.env.user.name, self.env.uid)
        self.search([('user_id', '=', self.env.uid)]).unlink()
