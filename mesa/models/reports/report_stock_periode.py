# -*- coding: utf-8 -*-
import logging
from odoo import models, fields, api

_logger = logging.getLogger(__name__)

class SnkReportStockPeriode(models.Model):
    _name = 'snk.report.stock.periode'
    _description = 'Report Stock Of Periode Summary'
    _order = 'site_id, analytic_id, default_code, product_id'

    # Filter Context Info
    user_id = fields.Many2one('res.users', string='Generated By', index=True, readonly=True)
    site_id = fields.Many2one('snk.site', string='Site', index=True, readonly=True)
    
    # Master Data
    product_id = fields.Many2one('product.product', string='Product Variant', index=True, readonly=True)
    product_template_id = fields.Many2one('product.template', string='Product Template', index=True, readonly=True)
    default_code = fields.Char(string='Variant Reference', readonly=True)
    template_default_code = fields.Char(string='Template Reference', readonly=True)
    
    category_id = fields.Many2one('product.category', string='Category', readonly=True)
    analytic_id = fields.Many2one('account.analytic.account', string='Brand', readonly=True)
    snk_grade_id = fields.Many2one('snk.product.grade', string='Grade', readonly=True)
    
    period_name = fields.Char(string='Periode', readonly=True)
    period_date = fields.Date(string='Period Sort Date', readonly=True)
    
    # Balances & Mutations
    opening_balance = fields.Float(string='Stok Awal', readonly=True, digits='Product Unit of Measure')
    qty_in = fields.Float(string='IN', readonly=True, digits='Product Unit of Measure')
    qty_sales_return = fields.Float(string='RETUR SALES', readonly=True, digits='Product Unit of Measure')
    qty_sales = fields.Float(string='SALES', readonly=True, digits='Product Unit of Measure')
    qty_out = fields.Float(string='OUT', readonly=True, digits='Product Unit of Measure')
    qty_adj_in = fields.Float(string='ADJ IN', readonly=True, digits='Product Unit of Measure')
    qty_adj_out = fields.Float(string='ADJ OUT', readonly=True, digits='Product Unit of Measure')
    ending_balance = fields.Float(string='Stok Akhir', readonly=True, digits='Product Unit of Measure')
    
    # Pricing
    currency_id = fields.Many2one('res.currency', string='Currency', compute='_compute_currency')
    price_unit = fields.Monetary(string='Unit Price', readonly=True, currency_field='currency_id')
    total_amount = fields.Monetary(string='Total Amount', readonly=True, currency_field='currency_id')

    def _compute_currency(self):
        for record in self:
            record.currency_id = self.env.company.currency_id

    @api.model
    def _clean_previous_reports(self):
        """ Membersihkan data milik user yang sedang mengeksekusi report. """
        self.search([('user_id', '=', self.env.uid)]).unlink()
