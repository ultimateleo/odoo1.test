# -*- coding: utf-8 -*-
import logging
from odoo import models, fields

_logger = logging.getLogger(__name__)


class ReportSTOSummary(models.Model):
    """
    Tabel fisik (bukan transient) menyimpan hasil generate STO Summary per user.
    Arsitektur: buffer table yang diisi via raw SQL dari wizard, 
    ditampilkan via list/pivot view dengan domain per user.
    """
    _name = 'report.sto.summary'
    _description = 'STO Summary Report Buffer'
    _order = 'delivery_no, id'

    # =====================================================================
    # Ownership — setiap user hanya lihat data miliknya
    # =====================================================================
    user_id = fields.Many2one(
        'res.users', string='Generated By',
        index=True, required=True, ondelete='cascade',
    )

    # =====================================================================
    # Delivery Info
    # =====================================================================
    delivery_no = fields.Char('Delivery No', index=True)
    delivery_picking_id = fields.Char('Delivery Picking', index=True)
    site_id = fields.Char('Source Site Delivery', index=True)
    site_name = fields.Char('Source Site Name Delivery')
    destination_site_id = fields.Char('Destination Site Delivery', index=True)
    destination_site_name = fields.Char('Destination Site Name Delivery')
    destination_name = fields.Char('Destination Name Delivery')
    brands = fields.Char('Brands Delivery')
    no_dus = fields.Char('No Dus Delivery')
    requisitioner = fields.Char('Requisitioner Delivery')
    state = fields.Char('Status Delivery', index=True)

    delivery_date = fields.Datetime('Delivery Date', index=True)
    sto_date = fields.Datetime('STO Date Delivery', index=True)
    validate_date = fields.Datetime('Validate Date Delivery')

    demand_qty = fields.Float('Demand Delivery', digits='Product Unit of Measure')
    actual_qty = fields.Float('Actual Quantity Delivery', digits='Product Unit of Measure')
    physical_delivery_date = fields.Datetime('Physical Delivery Date')

    # =====================================================================
    # Ekspedisi Info
    # =====================================================================
    carrier_name = fields.Char('Ekspedisi')
    city_name = fields.Char('City')
    district_name = fields.Char('District')
    tracking_ref = fields.Char('Resi')
    shipping_cost = fields.Float('Biaya Ekspedisi')
    shipping_weight = fields.Float('Berat')
    total_shipping_cost = fields.Float('Total Biaya Ekspedisi')
    bill_no = fields.Char('Bill No')

    # =====================================================================
    # Receipt Info
    # =====================================================================
    receipt_no = fields.Char('Receipt References')
    receipt_picking_id = fields.Char('Receipt References', index=True)
    receipt_date = fields.Datetime('First Receipt Date')
    receipt_qty = fields.Float('Received Quantity', digits='Product Unit of Measure')
    physical_receipt_date = fields.Datetime('Last Physical Receipt Date')

    # =====================================================================
    # Computed / Summary
    # =====================================================================
    jumlah_hari = fields.Integer('Jumlah Hari')
    akurat = fields.Float('Receipt Progress (%)', group_operator='avg')

    # =====================================================================
    # Additional Info
    # =====================================================================
    remarks = fields.Char('Remarks')
    notes = fields.Text('Notes')
    total_amount = fields.Float('Total Amount')
    net_amount = fields.Float('Net Amount')

    # POS & Status Info
    snk_pos_ref = fields.Char(string='POS Document', index=True)
    pos_status_site = fields.Selection([("inactive","Inactive"),("active","Active"),("gudang","Gudang")], string='POS Status Site')
    receipt_status = fields.Char(string='Status GR', index=True)

